    <section id="s2" class="section">
      <div class="section-number">2.</div>
      <div class="section-body">
        <h2>Comment nous protégeons vos données</h2>
        <p>Nous appliquons des principes de confidentialité par conception et par défaut, en limitant l’accès aux données et en utilisant des mesures techniques et organisationnelles adaptées.</p>
        <div class="callout">Nos équipes effectuent des audits réguliers et révisent nos mesures de sécurité pour traiter les nouveaux risques.</div>
      </div>
    </section>

    <section id="s3" class="section">
      <div class="section-number">3.</div>
      <div class="section-body">
        <h2>Vos droits</h2>
        <p>Selon votre juridiction, vous pouvez exercer des droits tels que : accès, rectification, suppression, limitation, opposition, portabilité et retrait du consentement.</p>
        <p class="subnote">Pour exercer vos droits, contactez notre Délégué à la protection des données à <a href="mailto:dataprotection@fifa.org">dataprotection@fifa.org</a>.</p>
      </div>
    </section>

    <section id="s4" class="section">
      <div class="section-number">4.</div>
      <div class="section-body">
        <h2>Bases légales du traitement</h2>
        <p>Nous traitons les données personnelles sur plusieurs bases légales, notamment le consentement, l’exécution d’un contrat, l’obligation légale et nos intérêts légitimes.</p>
      </div>
    </section>

    <section id="s5" class="section">
      <div class="section-number">5.</div>
      <div class="section-body">
        <h2>Quelles données nous collectons</h2>
        <p>Nous pouvons collecter :</p>
        <ul>
          <li>Informations d’identification : nom, adresse e‑mail, coordonnées de contact.</li>
          <li>Données de compte et d’utilisation : identifiants, préférences, historique d’interaction.</li>
          <li>Données de paiement lorsque vous effectuez des achats.</li>
          <li>Données techniques et de navigation (cookies, logs, adresse IP).</li>
          <li>Données publiques ou partagées via les réseaux sociaux si vous utilisez ces options.</li>
        </ul>
      </div>
    </section>

